-- Himmel Pharmaceutical Sales Management System: shared PostgreSQL schema.
-- Ported from the desktop app's SQLite schema. Safe to run on every migration:
-- tables/indexes use IF NOT EXISTS, functions use CREATE OR REPLACE, views and triggers are recreated.
--
-- Column types deliberately mirror the SQLite version so the UI receives the same values as before:
-- dates/timestamps stay TEXT ('YYYY-MM-DD' / 'YYYY-MM-DD HH:MM:SS'), flags stay 0/1 integers,
-- money stays double precision (SQLite REAL).

-- ─── Helper functions ───────────────────────────────────────────────────────

-- Same format as SQLite CURRENT_TIMESTAMP (UTC, 'YYYY-MM-DD HH:MM:SS').
CREATE OR REPLACE FUNCTION himmel_now_text() RETURNS text
LANGUAGE sql STABLE AS $$
  SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
$$;

-- Equivalent of SQLite date(text): first 10 characters as a date, NULL when not a date.
CREATE OR REPLACE FUNCTION himmel_date(value text) RETURNS date
LANGUAGE sql STABLE AS $$
  SELECT CASE
    WHEN value ~ '^\s*[0-9]{4}-[0-9]{2}-[0-9]{2}' THEN substring(btrim(value) from 1 for 10)::date
    ELSE NULL
  END
$$;

-- Equivalent of SQLite CAST(x AS REAL) for JSON values: NULL stays NULL, non-numbers become 0.
CREATE OR REPLACE FUNCTION himmel_num(value text) RETURNS numeric
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN value IS NULL THEN NULL
    WHEN value ~ '^\s*[-+]?([0-9]+\.?[0-9]*|\.[0-9]+)([eE][-+]?[0-9]+)?\s*$' THEN btrim(value)::numeric
    ELSE 0
  END
$$;

-- json_each() only ever iterated arrays here; anything else yields no rows.
CREATE OR REPLACE FUNCTION himmel_json_array(value jsonb) RETURNS jsonb
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN jsonb_typeof(value) = 'array' THEN value ELSE '[]'::jsonb END
$$;

CREATE OR REPLACE FUNCTION himmel_json_array(value text) RETURNS jsonb
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
  IF value IS NULL THEN
    RETURN '[]'::jsonb;
  END IF;
  RETURN himmel_json_array(value::jsonb);
EXCEPTION WHEN others THEN
  RETURN '[]'::jsonb;
END
$$;

-- ─── Authentication (was users.db) ──────────────────────────────────────────

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  full_name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('Admin', 'Manager', 'Rep', 'Sales Representative')),
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT himmel_now_text(),
  updated_at TEXT NOT NULL DEFAULT himmel_now_text(),
  last_login TEXT,
  failed_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until TEXT,
  force_password_change SMALLINT NOT NULL DEFAULT 0,
  -- Incremented when credentials change; older login tokens stop working.
  session_version INTEGER NOT NULL DEFAULT 0
);
-- Usernames were COLLATE NOCASE in SQLite.
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower ON users (LOWER(username));

CREATE TABLE IF NOT EXISTS system_security (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TEXT NOT NULL DEFAULT himmel_now_text()
);

-- Browser sessions. The cookie holds a random token; only its SHA-256 hash is stored, so a
-- leaked copy of this table cannot be used to sign in. kind 'recovery' is the short-lived
-- emergency recovery session (no user).
CREATE TABLE IF NOT EXISTS sessions (
  id_hash TEXT PRIMARY KEY,
  kind TEXT NOT NULL DEFAULT 'user' CHECK (kind IN ('user', 'recovery')),
  user_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
  -- Copy of users.session_version at sign-in: a password change or disabled account ends the session.
  session_version INTEGER NOT NULL DEFAULT 0,
  csrf_token TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL,
  ip TEXT,
  user_agent TEXT
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions (expires_at);

-- Attempt counters for sign-in and emergency recovery, shared by every server instance
-- (serverless hosting runs many short-lived copies, so in-memory counters are not enough).
CREATE TABLE IF NOT EXISTS rate_limits (
  key TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  reset_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rate_limits_reset ON rate_limits (reset_at);

