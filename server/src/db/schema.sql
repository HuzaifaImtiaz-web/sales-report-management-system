  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year_name TEXT NOT NULL UNIQUE,
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL,
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT himmel_now_text(),
  updated_at TEXT NOT NULL DEFAULT himmel_now_text(),
  CHECK (start_date <= end_date)
);
CREATE INDEX IF NOT EXISTS idx_business_years_active ON business_years (is_active);

CREATE TABLE IF NOT EXISTS unit_types (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL DEFAULT himmel_now_text(),
  updated_at TEXT NOT NULL DEFAULT himmel_now_text()
);

CREATE TABLE IF NOT EXISTS divisions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL DEFAULT himmel_now_text(),
  updated_at TEXT NOT NULL DEFAULT himmel_now_text()
);

CREATE TABLE IF NOT EXISTS groups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  division_id INTEGER REFERENCES divisions (id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  description TEXT,
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT himmel_now_text(),
  updated_at TEXT NOT NULL DEFAULT himmel_now_text()
);
CREATE INDEX IF NOT EXISTS idx_groups_active ON groups (is_active);

CREATE TABLE IF NOT EXISTS products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  division_id INTEGER NOT NULL REFERENCES divisions (id) ON DELETE RESTRICT,
  group_id INTEGER NOT NULL REFERENCES groups (id) ON DELETE RESTRICT,
  product_code TEXT NOT NULL UNIQUE,
  brand_name TEXT NOT NULL,
  generic_name TEXT,
  strength TEXT,
  dosage_form TEXT,
  registration_no TEXT UNIQUE,
  manufacturer TEXT,
  pack_size INTEGER NOT NULL CHECK (pack_size > 0),
  unit_type_id INTEGER NOT NULL REFERENCES unit_types (id) ON DELETE RESTRICT,
  tp DOUBLE PRECISION NOT NULL CHECK (tp >= 0),
  mrp DOUBLE PRECISION NOT NULL CHECK (mrp >= 0),
  description TEXT,
  status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive', 'Discontinued')),
  created_at TEXT NOT NULL DEFAULT himmel_now_text(),
  updated_at TEXT NOT NULL DEFAULT himmel_now_text(),
  -- Generated columns kept for backward compatibility (same as the SQLite schema).
  name TEXT GENERATED ALWAYS AS (brand_name) STORED,
  code TEXT GENERATED ALWAYS AS (product_code) STORED,
  pack_price DOUBLE PRECISION GENERATED ALWAYS AS (tp) STORED,
  pack_size_qty INTEGER GENERATED ALWAYS AS (pack_size) STORED,
  per_unit_price DOUBLE PRECISION GENERATED ALWAYS AS (tp / pack_size::double precision) STORED,
  is_active INTEGER GENERATED ALWAYS AS (CASE WHEN status = 'Active' THEN 1 ELSE 0 END) STORED
);
CREATE INDEX IF NOT EXISTS idx_products_status ON products (status);

CREATE TABLE IF NOT EXISTS areas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
