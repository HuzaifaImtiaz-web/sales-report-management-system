-- Expands each target's Area -> Team Member percentage tree into one row per team member.
CREATE VIEW view_team_member_targets AS
SELECT
  pt.id AS product_target_id,
  pt.business_year_id,
  pt.product_id,
  tm_db.id AS team_member_id,
  tm_db.name AS team_member_name,
  area_db.id AS area_id,
  area_db.name AS area_name,
  ROUND(
    pt.annual_target_qty
    * (himmel_num(area.value ->> 'percentage') / 100.0)
    * (himmel_num(tm.value ->> 'percentage') / 100.0)
  )::integer AS target_qty
FROM product_targets pt
CROSS JOIN LATERAL jsonb_array_elements(himmel_json_array(pt.areas_distribution)) AS area(value)
CROSS JOIN LATERAL jsonb_array_elements(himmel_json_array(area.value -> 'teamMembers')) AS tm(value)
LEFT JOIN team_members tm_db ON tm_db.name = tm.value ->> 'name'
LEFT JOIN areas area_db ON area_db.name = area.value ->> 'areaName';

CREATE VIEW view_sales_summary AS
SELECT
  oi.id AS order_item_id,
  oi.order_id,
  o.order_number,
  o.order_date,
  o.status AS order_status,
  tm.id AS team_member_id,
  tm.name AS team_member_name,
  p.id AS product_id,
  p.brand_name AS product_name,
  a.id AS area_id,
  a.name AS area_name,
  oi.quantity,
  oi.unit_price,
  oi.total_price
FROM order_items oi
JOIN orders o ON oi.order_id = o.id
JOIN team_members tm ON o.team_member_id = tm.id
JOIN products p ON oi.product_id = p.id
JOIN areas a ON o.area_id = a.id;

CREATE VIEW view_target_achievements AS
SELECT
  v.product_target_id AS target_id,
  v.business_year_id,
  byr.year_name,
  v.team_member_id,
  v.team_member_name,
  v.product_id,
  p.brand_name AS product_name,
  v.target_qty,
  (v.target_qty * COALESCE(p.tp, 0.0)) AS target_value,
  COALESCE(actual.qty, 0) AS actual_qty,
  COALESCE(actual.value, 0.0) AS actual_value,
  CASE
    WHEN v.target_qty = 0 THEN 0.0
    ELSE ROUND((COALESCE(actual.qty, 0) * 100.0) / v.target_qty, 2)
  END AS qty_achievement_percent,
  CASE
    WHEN (v.target_qty * COALESCE(p.tp, 0.0)) = 0.0 THEN 0.0
    ELSE ROUND(((COALESCE(actual.value, 0.0) * 100.0) / (v.target_qty * COALESCE(p.tp, 0.0)))::numeric, 2)
  END AS value_achievement_percent
FROM view_team_member_targets v
JOIN business_years byr ON v.business_year_id = byr.id
JOIN products p ON v.product_id = p.id
LEFT JOIN (
  SELECT
    o.team_member_id,
    oi.product_id,
    byr.id AS business_year_id,
    SUM(oi.quantity) AS qty,
    SUM(oi.total_price) AS value
  FROM order_items oi
  JOIN orders o ON oi.order_id = o.id
  JOIN business_years byr
    ON himmel_date(o.order_date) BETWEEN himmel_date(byr.start_date) AND himmel_date(byr.end_date)
  WHERE o.status = 'Completed'
  GROUP BY o.team_member_id, oi.product_id, byr.id
) actual
  ON v.team_member_id = actual.team_member_id
 AND v.product_id = actual.product_id
 AND v.business_year_id = actual.business_year_id;

CREATE VIEW view_team_performance AS
SELECT
  tm.id AS team_member_id,
  tm.name AS team_member_name,
  tm.role,
  COUNT(o.id) AS total_orders,
  SUM(CASE WHEN o.status = 'Completed' THEN 1 ELSE 0 END) AS completed_orders,
  COALESCE(SUM(CASE WHEN o.status = 'Completed' THEN o.total_amount ELSE 0.0 END), 0.0) AS total_sales_value,
  COALESCE(AVG(CASE WHEN o.status = 'Completed' THEN o.total_amount ELSE NULL END), 0.0) AS average_order_value
FROM team_members tm
LEFT JOIN orders o ON tm.id = o.team_member_id
GROUP BY tm.id;

CREATE VIEW view_monthly_sales AS
SELECT
  to_char(himmel_date(o.order_date), 'YYYY-MM') AS sales_month,
  COUNT(o.id) AS total_orders,
  COALESCE(SUM(CASE WHEN o.status = 'Completed' THEN o.total_amount ELSE 0.0 END), 0.0) AS total_sales
FROM orders o
WHERE o.status = 'Completed'
GROUP BY 1;

-- ─── Triggers ───────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION himmel_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := himmel_now_text();
  RETURN NEW;
END
$$;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'users', 'business_years', 'unit_types', 'divisions', 'groups', 'products', 'areas',
    'team_members', 'doctors', 'institutions', 'product_targets', 'orders', 'order_items', 'settings'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%s_updated ON %I', t, t);
    EXECUTE format(
      'CREATE TRIGGER trg_%s_updated BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION himmel_touch_updated_at()',
      t, t
    );
  END LOOP;
END
$$;

-- Keeps orders.total_amount equal to the sum of its items (trg_order_items_insert/update/delete in SQLite).
CREATE OR REPLACE FUNCTION himmel_sync_order_total() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  affected_order integer;
BEGIN
  IF TG_OP = 'DELETE' THEN
    affected_order := OLD.order_id;
  ELSE
    affected_order := NEW.order_id;
  END IF;

  UPDATE orders
     SET total_amount = (SELECT COALESCE(SUM(total_price), 0.0) FROM order_items WHERE order_id = affected_order)
   WHERE id = affected_order;

  IF TG_OP = 'UPDATE' AND OLD.order_id IS DISTINCT FROM NEW.order_id THEN
    UPDATE orders
       SET total_amount = (SELECT COALESCE(SUM(total_price), 0.0) FROM order_items WHERE order_id = OLD.order_id)
     WHERE id = OLD.order_id;
  END IF;

  RETURN NULL;
END
$$;

DROP TRIGGER IF EXISTS trg_order_items_total ON order_items;
CREATE TRIGGER trg_order_items_total
  AFTER INSERT OR UPDATE OR DELETE ON order_items
  FOR EACH ROW EXECUTE FUNCTION himmel_sync_order_total();

-- Same rules as trg_product_targets_validate_insert/update in SQLite.
CREATE OR REPLACE FUNCTION himmel_validate_target_distribution() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  area_total numeric;
  has_bad_area boolean;
BEGIN
  SELECT COALESCE(SUM(himmel_num(area.value ->> 'percentage')), 0)
    INTO area_total
    FROM jsonb_array_elements(himmel_json_array(NEW.areas_distribution)) AS area(value);

  IF area_total <> 100 THEN
    RAISE EXCEPTION 'Validation Error: Total Area percentages must sum to exactly 100%%.';
  END IF;

  SELECT EXISTS (
    SELECT 1
      FROM jsonb_array_elements(himmel_json_array(NEW.areas_distribution)) AS area(value)
     WHERE (
       SELECT COALESCE(SUM(himmel_num(tm.value ->> 'percentage')), 0)
         FROM jsonb_array_elements(himmel_json_array(area.value -> 'teamMembers')) AS tm(value)
     ) <> 100
  ) INTO has_bad_area;

  IF has_bad_area THEN
    RAISE EXCEPTION 'Validation Error: Team Member percentages inside each Area must sum to exactly 100%%.';
  END IF;

  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS trg_product_targets_validate ON product_targets;
CREATE TRIGGER trg_product_targets_validate
  BEFORE INSERT OR UPDATE ON product_targets
  FOR EACH ROW EXECUTE FUNCTION himmel_validate_target_distribution();
