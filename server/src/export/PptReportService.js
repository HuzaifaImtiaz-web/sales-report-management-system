/**
 * Enterprise PowerPoint Report Engine Foundation Service
 * Himmel Pharmaceutical Sales Management System
 * 
 * Handles enterprise PPT report generation adhering to theme standards,
 * master layout helpers, asset manager, and report metadata.
 */

const pptxgen = require('pptxgenjs');
const config = require('../config');

const THEME = require('./ppt/theme');
const AssetManager = require('./ppt/assets');
const layout = require('./ppt/layout');

class PptReportService {
  constructor() {
    this.theme = THEME;
    this.assets = AssetManager;
    this.layout = layout;
  }

  getSoftwareVersion() {
    return config.version;
  }

  /**
   * Build complete Report Metadata object (dates in the requesting user's time zone)
   */
  createMetadata(reportName, user = 'System', timeZone = 'UTC') {
    const now = new Date();
    return {
      companyName: AssetManager.getCompanyName(),
      softwareName: 'Himmel Pharmaceutical Sales Management System',
      reportName: AssetManager.getReportTitle(reportName),
      generatedDate: now.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone }),
      generatedTime: now.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', second: '2-digit', timeZone }),
      softwareVersion: this.getSoftwareVersion(),
      generatedBy: user || 'System'
    };
  }

  /**
   * Slide 1: Cover Slide Framework
   */
  buildCoverSlide(pptx, metadata) {
    const slide = pptx.addSlide();
    slide.background = { color: THEME.colors.secondary };

    // Header Accent Line
    slide.addShape('rect', {
      x: 0, y: 0, w: '100%', h: 0.15,
      fill: { color: THEME.colors.primary },
      line: { color: THEME.colors.primary, width: 0 }
    });

    // Company Name
    slide.addText(metadata.companyName.toUpperCase(), {
      x: 0.8, y: 1.5, w: '90%', h: 0.5,
      fontSize: 26, fontFace: THEME.typography.fontFace,
      color: THEME.colors.white, bold: true
    });

    // Report Title
    slide.addText(metadata.reportName, {
      x: 0.8, y: 2.2, w: '90%', h: 0.6,
      fontSize: 20, fontFace: THEME.typography.fontFace,
      color: THEME.colors.primary, bold: true
    });

    // Subtitle / System Name
    slide.addText(`${metadata.softwareName} (v${metadata.softwareVersion})`, {
      x: 0.8, y: 3.0, w: '90%', h: 0.4,
      fontSize: THEME.typography.subtitleSize, fontFace: THEME.typography.fontFace,
      color: THEME.colors.mutedText
    });

    // Metadata Footer Box on Cover
    const metaStr = `Generated By: ${metadata.generatedBy}   |   Date: ${metadata.generatedDate} ${metadata.generatedTime}   |   Version: v${metadata.softwareVersion}`;
    slide.addText(metaStr, {
      x: 0.8, y: 5.2, w: '90%', h: 0.4,
      fontSize: THEME.typography.bodySize, fontFace: THEME.typography.fontFace,
      color: THEME.colors.mutedText
    });

    return slide;
  }

  /**
   * Slide 2: Executive Summary Framework
   */
  buildExecutiveSummarySlide(pptx, metadata, data = {}, pageNum = 2, totalPages = 6) {
    const slide = pptx.addSlide();
    slide.background = { color: THEME.colors.lightGray };

    layout.createHeader(slide, 'Executive Summary');
    layout.createTitle(slide, 'Executive Summary & Key Metrics', 'High-level business overview and performance summary.');
    layout.createFooter(slide, pageNum, totalPages);

    const summary = data.summary || { totalRecords: 0, totalAmount: 0, totalQty: 0 };

    // KPI Cards Layout
    const kpis = [
      { title: 'Total System Records', val: summary.totalRecords ? summary.totalRecords.toLocaleString() : '0', color: THEME.colors.accent },
      { title: 'Total Net Value (Rs)', val: summary.totalAmount > 0 ? `Rs ${summary.totalAmount.toLocaleString(undefined, { minimumFractionDigits: 2 })}` : 'N/A', color: THEME.colors.primary },
      { title: 'Total Target / Quantity', val: summary.totalQty > 0 ? summary.totalQty.toLocaleString() : 'N/A', color: THEME.colors.success }
    ];

    kpis.forEach((kpi, idx) => {
      const xPos = 0.5 + idx * 4.1;
      slide.addShape('rect', {
        x: xPos, y: 1.4, w: 3.8, h: 1.8,
        fill: { color: THEME.colors.white },
        line: { color: THEME.colors.mediumGray, width: THEME.common.tableStyles.borderWidth }
      });
      slide.addText(kpi.title.toUpperCase(), {
        x: xPos + 0.3, y: 1.6, w: 3.2, h: 0.3,
        fontSize: THEME.typography.smallSize, fontFace: THEME.typography.fontFace,
        color: THEME.colors.subtleText, bold: true
      });
      slide.addText(kpi.val, {
        x: xPos + 0.3, y: 2.1, w: 3.2, h: 0.7,
        fontSize: 18, fontFace: THEME.typography.fontFace,
        color: kpi.color, bold: true
      });
    });

    // Executive Highlights Box
    slide.addText('Executive Highlights & System Scope:', {
      x: 0.5, y: 3.6, w: 9.0, h: 0.4,
      fontSize: THEME.typography.bodySize + 2, fontFace: THEME.typography.fontFace,
      color: THEME.colors.secondary, bold: true
    });

    const bullets = [
      `Module '${metadata.reportName}' compiled via ${metadata.softwareName}.`,
      `Total of ${summary.totalRecords.toLocaleString()} verified records in active dataset.`,
      `Generated by ${metadata.generatedBy} on ${metadata.generatedDate} at ${metadata.generatedTime}.`
    ];

    bullets.forEach((b, i) => {
      slide.addText(`• ${b}`, {
        x: 0.8, y: 4.1 + i * 0.45, w: 11.5, h: 0.35,
        fontSize: THEME.typography.bodySize, fontFace: THEME.typography.fontFace,
        color: THEME.colors.darkGray
      });
    });

    return slide;
  }

  /**
   * Slide 3: Charts Slide Framework
   */
  buildChartsSlide(pptx, metadata, data = {}, pageNum = 3, totalPages = 6) {
    const slide = pptx.addSlide();
    slide.background = { color: THEME.colors.white };

    layout.createHeader(slide, 'Visual Analytics');
    layout.createTitle(slide, 'Visual Graphical Analytics', 'Chart overview of dataset key performance indicators.');
    layout.createFooter(slide, pageNum, totalPages);

    const rows = (data.rows || []).slice(0, 8);
    const labels = rows.length > 0
      ? rows.map(r => r.product_name || r.doctor_name || r.name || r.order_number || r.sales_month || `Item #${r.id}`)
      : ['Sample A', 'Sample B', 'Sample C', 'Sample D'];
    const values = rows.length > 0
      ? rows.map(r => Number(r.tp || r.total_amount || r.annual_target || r.total_sales || 100))
      : [120, 250, 180, 310];

    const chartData = [{
      name: 'Metrics',
      labels,
      values
    }];

    slide.addChart(pptx.ChartType.bar, chartData, {
      x: 0.5, y: 1.4, w: 12.33, h: 5.2,
      barDir: 'col',
      chartColors: [THEME.colors.primary],
      showValue: true,
      valGridLine: { color: THEME.colors.mediumGray, style: 'dash' }
    });

    return slide;
  }

  /**
   * Slide 4: Analysis Slide Framework
   */
  buildAnalysisSlide(pptx, metadata, data = {}, pageNum = 4, totalPages = 6) {
    const slide = pptx.addSlide();
    slide.background = { color: THEME.colors.lightGray };

    layout.createHeader(slide, 'Deep Analysis');
    layout.createTitle(slide, 'Analytical Findings & Insights', 'Detailed structural and trend evaluation.');
    layout.createFooter(slide, pageNum, totalPages);

    // Analysis Cards
    const insights = [
      { title: 'Data Distribution', desc: 'Dataset demonstrates consistent distribution across designated categories and operational filters.' },
      { title: 'Performance Trends', desc: 'Financial indicators show stable target tracking and record verification.' },
      { title: 'System Compliance', desc: 'Audit logs and transactions adhere strictly to enterprise compliance standards.' }
    ];

    insights.forEach((item, idx) => {
      const yPos = 1.4 + idx * 1.7;
      slide.addShape('rect', {
        x: 0.5, y: yPos, w: 12.33, h: 1.4,
        fill: { color: THEME.colors.white },
        line: { color: THEME.colors.mediumGray, width: THEME.common.tableStyles.borderWidth }
      });
      slide.addText(item.title, {
        x: 0.8, y: yPos + 0.2, w: 11.5, h: 0.35,
        fontSize: THEME.typography.bodySize + 2, fontFace: THEME.typography.fontFace,
        color: THEME.colors.primary, bold: true
      });
      slide.addText(item.desc, {
        x: 0.8, y: yPos + 0.65, w: 11.5, h: 0.5,
        fontSize: THEME.typography.bodySize, fontFace: THEME.typography.fontFace,
        color: THEME.colors.darkGray
      });
    });

    return slide;
  }

  /**
   * Slide 5: Tables Slide Framework
   */
  buildTablesSlide(pptx, metadata, data = {}, pageNum = 5, totalPages = 6) {
    const slide = pptx.addSlide();
    slide.background = { color: THEME.colors.white };

    layout.createHeader(slide, 'Data Records');
    layout.createTitle(slide, `${metadata.reportName} Master Data Table`, 'Tabular presentation of verified system records.');
    layout.createFooter(slide, pageNum, totalPages);

    const cols = data.columns || [
      { header: 'ID', key: 'id', width: 10, type: 'number' },
      { header: 'Name', key: 'name', width: 30, type: 'text' },
      { header: 'Status', key: 'status', width: 15, type: 'text' }
    ];
    const rows = data.rows || [];

    const headerCells = cols.map(c => ({
      text: c.header,
      options: {
        fill: THEME.common.tableStyles.headerFill,
        color: THEME.common.tableStyles.headerTextColor,
        bold: THEME.common.tableStyles.headerFontBold,
        fontSize: THEME.common.tableStyles.headerFontSize,
        align: c.type === 'currency' || c.type === 'number' ? 'right' : 'left'
      }
    }));

    const bodyRows = rows.slice(0, 10).map((row, rIdx) => {
      return cols.map(col => {
        let val = row[col.key];
        if (col.type === 'currency') {
          val = val !== null && val !== undefined ? `Rs ${Number(val).toLocaleString()}` : 'Rs 0';
        } else if (val === null || val === undefined) {
          val = '—';
        } else {
          val = String(val);
        }
        return {
          text: val,
          options: {
            fontSize: THEME.common.tableStyles.rowFontSize,
            fill: rIdx % 2 === 1 ? THEME.common.tableStyles.rowAlternateFill : THEME.common.tableStyles.rowBaseFill,
            color: THEME.common.tableStyles.rowTextColor,
            align: col.type === 'currency' || col.type === 'number' ? 'right' : 'left'
          }
        };
      });
    });

    const fullTable = [headerCells, ...bodyRows];
    const colW = cols.map(c => Math.max(1.0, (c.width || 15) / 12));

    if (headerCells.length > 0) {
      slide.addTable(fullTable, {
        x: 0.5, y: 1.4, w: 12.33, colW, autoPage: true
      });
    }

    return slide;
  }

  /**
   * Slide 6: Closing Slide Framework
   */
  buildClosingSlide(pptx, metadata, pageNum = 6, totalPages = 6) {
    const slide = pptx.addSlide();
    slide.background = { color: THEME.colors.secondary };

    // Center Title
    slide.addText('REPORT EXECUTION COMPLETED', {
      x: 0.8, y: 2.0, w: '90%', h: 0.8,
      fontSize: 26, fontFace: THEME.typography.fontFace,
      color: THEME.colors.white, bold: true, align: 'center'
    });

    slide.addText(metadata.companyName, {
      x: 0.8, y: 2.9, w: '90%', h: 0.5,
      fontSize: 16, fontFace: THEME.typography.fontFace,
      color: THEME.colors.primary, bold: true, align: 'center'
    });

    slide.addText(`${metadata.softwareName} (v${metadata.softwareVersion})`, {
      x: 0.8, y: 3.5, w: '90%', h: 0.4,
      fontSize: THEME.typography.subtitleSize, fontFace: THEME.typography.fontFace,
      color: THEME.colors.mutedText, align: 'center'
    });

    slide.addText('Confidential  |  Internal Management & Board Presentation Use Only', {
      x: 0.8, y: 5.2, w: '90%', h: 0.4,
      fontSize: THEME.typography.bodySize, fontFace: THEME.typography.fontFace,
      color: THEME.colors.subtleText, align: 'center'
    });

    return slide;
  }

  /**
   * Main Report Generator Handler
   * Assembles PowerPoint report following standard framework:
   * Cover -> Executive Summary -> Charts -> Analysis -> Tables -> Closing
   */
  async generateReport({ reportType, data = {}, user = 'System', timeZone = 'UTC' }) {
    const pptx = new pptxgen();
    pptx.layout = 'LAYOUT_16x9';

    const metadata = this.createMetadata(data.title || reportType, user, timeZone);

    // Build standard slide structure
    this.buildCoverSlide(pptx, metadata);
    this.buildExecutiveSummarySlide(pptx, metadata, data, 2, 6);
    this.buildChartsSlide(pptx, metadata, data, 3, 6);
    this.buildAnalysisSlide(pptx, metadata, data, 4, 6);
    this.buildTablesSlide(pptx, metadata, data, 5, 6);
    this.buildClosingSlide(pptx, metadata, 6, 6);

    return pptx.write({ outputType: 'nodebuffer' });
  }

  /**
   * Generate Master Enterprise Multi-Module PPT Report
   */
  async generateMasterReport({ masterData = {}, user = 'System', timeZone = 'UTC' }) {
    const pptx = new pptxgen();
    pptx.layout = 'LAYOUT_16x9';

    const metadata = this.createMetadata('Master Enterprise System Export', user, timeZone);
    const modules = masterData.modules || {};
    const totalModuleCount = Object.keys(modules).length;
    const totalPages = 3 + totalModuleCount + 1; // Cover + ExecSummary + Overview + Modules + Closing

    // 1. Cover
    this.buildCoverSlide(pptx, metadata);

    // 2. Executive Summary
    this.buildExecutiveSummarySlide(pptx, metadata, masterData, 2, totalPages);

    // 3. Module Slides
    let currentSlide = 3;
    for (const [modName, modData] of Object.entries(modules)) {
      const modMetadata = { ...metadata, reportName: modName };
      this.buildTablesSlide(pptx, modMetadata, modData, currentSlide, totalPages);
      currentSlide++;
    }

    // 4. Closing
    this.buildClosingSlide(pptx, metadata, currentSlide, totalPages);

    return pptx.write({ outputType: 'nodebuffer' });
  }
}

module.exports = new PptReportService();
